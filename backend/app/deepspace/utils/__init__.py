"""DeepSpace Utilities Package.

Provides core utility modules for DeepSpace (AverQel KineSis backend):
- atomic_write: Atomic file operations with cross-process locking
- brand: Branded/nominal types for compile-time type safety
- chunked_list: Persistent append-only chunked lists with structural sharing
- code_language: File extension to syntax highlighting language mapping
- crypto: Browser-safe UUID and encoding utilities
- deque: Circular deque with auto-compact
- native_command: Native command execution & path opening
- output_retention: Bounded retention for model-facing output

All modules are designed to be zero-dependency (stdlib only) and
compatible with Python 3.11+.
"""

