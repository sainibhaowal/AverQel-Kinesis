"""A native Python implementation of the DeepSpace capability protocol.

The package is a Python port of the Harness Typert surface.  It has six
layers:

* ``errors``, ``json_value``, ``codecs``, ``principal``, ``owned``,
  ``resources``, ``invocation``, ``descriptors``, and ``decorators`` -
  the protocol: typed failures, lossless JSON, boundary codecs, caller
  identity, owned values, declared resources, ambient invocation, endpoint
  declarations, and the ``@remote``/``@remote_scope`` decorators;
* ``streams`` - a bidirectional stream with an uplink byte window;
* ``schema`` and ``reflection`` - lazily materialized schemas and runtime
  package reflection;
* ``registry`` - the local/remote descriptor stores, the atomic contribution
  lifecycle, lookup/Context/resource providers, subscriptions, and
  in-process invocation;
* ``loader`` - entry-point, module, and manifest discovery with mount and
  unmount;
* ``codegen`` - JSON Schema, manifest, and Python client artifacts with a
  freshness guard;
* ``bridge``, ``service``, and ``api`` - the live DeepSpace wiring: native
  tools, the Todo contract, the process singleton, authenticated capability
  transports, and registry introspection.

The package is additive.  Existing tools, plugins, task ledger, and session
events keep their current contracts; Typert describes and, where a caller
supplies an authenticated context, invokes them through the protocol.
"""

