"""Exercise the DeepSpace Office tool against installed native binaries.

Run explicitly with the real LibreOffice and Poppler packages installed; this
file is intentionally outside the default unit-test discovery path.
"""

from __future__ import annotations

import shutil
import zipfile
from pathlib import Path
from types import SimpleNamespace
from typing import cast

import pytest
from docx import Document
from openpyxl import Workbook, load_workbook

from app.deepspace.services.tools._base import ToolContext
from app.deepspace.services.tools.dependencies import workspace_dependencies
from app.deepspace.services.tools.office import _office_process


@pytest.mark.asyncio
async def test_real_libreoffice_poppler_export_recalculate_and_render(tmp_path: Path) -> None:
    dependencies = workspace_dependencies(SimpleNamespace(deepspace_runtime_manifest_path=""))
    office_runtime = dependencies["office_runtime"]
    office_binary = office_runtime["soffice"] or office_runtime["libreoffice"]
    renderer = office_runtime["pdftoppm"]
    assert (
        office_binary and Path(office_binary).is_file()
    ), "Install LibreOffice so this test exercises the real converter."
    assert (
        renderer and Path(renderer).is_file()
    ), "Install Poppler so this test exercises the real PDF renderer."
    assert shutil.which(Path(office_binary).name)
    assert shutil.which(Path(renderer).name)

    document_path = tmp_path / "memo.docx"
    document = Document()
    document.add_heading("DeepSpace Office runtime check", level=1)
    document.add_paragraph("Generated by a disposable native integration test.")
    document.save(str(document_path))

    workbook_path = tmp_path / "totals.xlsx"
    workbook = Workbook()
    sheet = workbook.active
    sheet["A1"] = 11
    sheet["A2"] = 31
    sheet["A3"] = "=SUM(A1:A2)"
    workbook.calculation.fullCalcOnLoad = True
    workbook.calculation.forceFullCalc = True
    workbook.calculation.calcMode = "auto"
    workbook.save(workbook_path)

    context = cast(
        ToolContext,
        SimpleNamespace(
            workspace_root=tmp_path,
            settings=SimpleNamespace(deepspace_runtime_manifest_path=""),
            sandbox_mode="workspace-write",
        ),
    )
    exported = await _office_process(
        {"operation": "export_pdf", "input_path": "memo.docx"}, context
    )
    assert exported["status"] == "ok", exported
    exported_pdf = tmp_path / exported["output_path"]
    assert exported_pdf.read_bytes().startswith(b"%PDF-")

    rendered = await _office_process(
        {"operation": "render_pages", "input_path": "memo.pdf", "page_limit": 2}, context
    )
    assert rendered["status"] == "ok", rendered
    page_paths = [tmp_path / value for value in rendered["pages"]]
    assert page_paths and page_paths[0].read_bytes().startswith(b"\x89PNG\r\n\x1a\n")

    recalculated = await _office_process(
        {"operation": "recalculate_workbook", "input_path": "totals.xlsx"}, context
    )
    assert recalculated["status"] == "ok", recalculated
    recalculated_path = tmp_path / recalculated["output_path"]
    assert zipfile.is_zipfile(recalculated_path)
    values = load_workbook(recalculated_path, data_only=True, read_only=True)
    try:
        assert values.active["A3"].value == 42
    finally:
        values.close()

    assert document_path.read_bytes() != exported_pdf.read_bytes()
    assert workbook_path.read_bytes() != recalculated_path.read_bytes()
